/**
 * Размеры мира — не константа: у формы карты они свои. Обычные карты
 * широкие и низкие (3200x720), «Башня» — узкая и высокая, чтобы целиком
 * помещаться в вертикальный экран телефона. Сцена зовёт applyWorld до
 * постройки чего бы то ни было; значения по умолчанию возвращаются каждый
 * раз, поэтому одна партия не протекает в другую.
 */
const WORLD_DEFAULT = {
  w: 3200, h: 720, ground: 675, water: 630, focus: 520,
  power: 1200,     // AIM_MAX_POWER: дальность при 45° = power²/g
  fallSafe: 100,
};

export function applyWorld(world = null) {
  const v = { ...WORLD_DEFAULT, ...(world ?? {}) };
  CFG.WORLD_W = v.w;
  CFG.WORLD_H = v.h;
  CFG.GROUND_BASE = v.ground;
  CFG.WATER_Y = v.water;
  CFG.DROWN_Y = v.water + 15;
  CFG.WORLD_FOCUS_Y = v.focus;
  CFG.AIM_MAX_POWER = v.power;
  CFG.FALL_SAFE = v.fallSafe;
}

/**
 * Подогнать логическую ширину под пропорции экрана.
 *
 * Мы держим постоянной высоту (720) и тянем ширину: тогда Phaser.Scale.FIT
 * вписывает канвас без чёрных полей по бокам, а игрок на вытянутом телефоне
 * видит больше поля по горизонтали — для артиллерии это прямая выгода.
 * Вызывать до создания Phaser.Game.
 */
export function fitViewToScreen(screenW, screenH, inset = null) {
  if (!screenW || !screenH) return CFG.VIEW_W;
  const i = inset ?? { left: 0, top: 0, right: 0, bottom: 0 };
  const safeW = Math.max(1, screenW - i.left - i.right);
  // Верхний отступ в высоту не входит: кнопки Telegram занимают только
  // углы, и панель боя идёт до самого верха, отступая от них по краям
  // — так в ландшафте. В портрете наоборот: вверху «чёлка» и кнопки
  // Telegram занимают всю ширину узкого экрана, панели рядом с ними не
  // поместиться, поэтому интерфейс целиком уходит под верхний отступ.
  const portrait = screenH - i.bottom > safeW;
  const top = portrait ? (i.top ?? 0) : 0;
  const safeH = Math.max(1, screenH - i.bottom - top);

  // Масштаб один в обеих ориентациях: короткая сторона безопасной области
  // — это VIEW_BASE логических пикселей, боец и кнопки одного размера, как
  // ни держи телефон. В ландшафте фиксирована высота и растёт ширина, в
  // портрете наоборот: там живут меню и лобби, а бой просит повернуть.
  // При повороте размер пересчитывается (main.js), второй раз — не в ущерб.
  const long = Math.max(safeW, safeH);
  const short = Math.min(safeW, safeH);
  const wanted = Math.round(CFG.VIEW_BASE * (long / short));
  if (portrait) {
    CFG.VIEW_W = CFG.VIEW_BASE;
    CFG.VIEW_H = Math.max(CFG.VIEW_BASE, Math.min(CFG.VIEW_H_MAX, wanted));
  } else if (wanted >= CFG.VIEW_W_MIN) {
    CFG.VIEW_H = CFG.VIEW_BASE;
    CFG.VIEW_W = Math.min(CFG.VIEW_W_MAX, wanted);
  } else {
    // Ландшафт, но уже 16:9 — ноутбук 16:10, планшет 4:3. Уже 1280 ширину
    // не сжимаем (интерфейс не влезет), а растим высоту: иначе FIT
    // вписывал 16:9 с чёрными полосами сверху и снизу. Миру это не мешает —
    // камера покажет над землёй больше неба.
    CFG.VIEW_W = CFG.VIEW_W_MIN;
    CFG.VIEW_H = Math.min(CFG.VIEW_H_MAX, Math.round(CFG.VIEW_W_MIN * (short / long)));
  }

  // Рамка: те же отступы в логических пикселях.
  // Логических пикселей на CSS-пиксель: по стороне, которая зафиксирована
  const k = portrait ? CFG.VIEW_W / safeW : CFG.VIEW_H / safeH;
  CFG.FRAME = {
    left: Math.round(i.left * k), top: Math.round(top * k),
    right: Math.round(i.right * k), bottom: Math.round(i.bottom * k),
  };
  CFG.CORNER = portrait ? 0 : Math.round((i.corner ?? 0) * k);
  return CFG.VIEW_W;
}

/** Размер канваса: логический экран плюс рамка. */
export function canvasSize() {
  const f = CFG.FRAME;
  return [CFG.VIEW_W + f.left + f.right, CFG.VIEW_H + f.top + f.bottom];
}

